"""Generate model and source documentation into README.md from the dbt manifest.

Everything between the DOCS:START and DOCS:END markers in README.md is
replaced; the rest of the file is left alone. Run it FROM THE REPO ROOT after
dbt has written analytics/target/manifest.json:

    cd analytics && uv run dbt parse && cd ..
    uv run python scripts/generate_docs.py

Descriptions, columns and tests come from analytics/models/*.yml, so edit
those files, not the generated section.
"""

import json
import re
import sys
from pathlib import Path

MANIFEST = Path("analytics/target/manifest.json")
README = Path("README.md")
START = "<!-- DOCS:START - generated by scripts/generate_docs.py, do not edit by hand -->"
END = "<!-- DOCS:END -->"


def cell(text):
    """Make text safe for a single Markdown table cell."""
    return " ".join((text or "").split()).replace("|", "\\|")


def describe_test(test):
    meta = test.get("test_metadata") or {}
    name = meta.get("name", test["name"])
    values = meta.get("kwargs", {}).get("values")
    label = f"{name}: {', '.join(map(str, values))}" if values else name
    if test["config"].get("severity", "ERROR").upper() == "WARN":
        label += " (warn)"
    return f"`{label}`"


def tests_by_column(manifest):
    """Map (node unique_id, column name) -> list of test labels."""
    found = {}
    for node in manifest["nodes"].values():
        if node["resource_type"] != "test" or not node.get("column_name"):
            continue
        parent = node.get("attached_node") or next(iter(node["depends_on"]["nodes"]), None)
        found.setdefault((parent, node["column_name"]), []).append(describe_test(node))
    return found


def columns_table(node, tests):
    if not node["columns"]:
        return "_No columns documented._\n"
    rows = ["| Column | Description | Tests |", "| --- | --- | --- |"]
    for col in node["columns"].values():
        labels = sorted(tests.get((node["unique_id"], col["name"]), []))
        rows.append(f"| `{col['name']}` | {cell(col.get('description'))} | {' '.join(labels)} |")
    return "\n".join(rows) + "\n"


def mermaid_id(unique_id):
    return re.sub(r"\W", "_", unique_id)


def lineage(models, sources, manifest):
    lines = ["```mermaid", "flowchart LR"]
    for src in sources:
        lines.append(f'    {mermaid_id(src["unique_id"])}[("{src["source_name"]}.{src["name"]}")]')
    for model in models:
        lines.append(f'    {mermaid_id(model["unique_id"])}["{model["name"]}"]')
    for model in models:
        for parent in manifest["parent_map"].get(model["unique_id"], []):
            if parent.startswith(("model.", "source.")):
                lines.append(f"    {mermaid_id(parent)} --> {mermaid_id(model['unique_id'])}")
    lines.append("```")
    return "\n".join(lines) + "\n"


def build_docs(manifest):
    project = manifest["metadata"].get("project_name", "analytics")
    models = sorted(
        (n for n in manifest["nodes"].values() if n["resource_type"] == "model" and n["package_name"] == project),
        key=lambda n: n["name"],
    )
    sources = sorted(
        (s for s in manifest["sources"].values() if s["package_name"] == project),
        key=lambda s: (s["source_name"], s["name"]),
    )
    tests = tests_by_column(manifest)
    test_count = sum(1 for n in manifest["nodes"].values() if n["resource_type"] == "test")

    out = [
        "## Data catalog\n",
        f"{len(sources)} sources, {len(models)} models and {test_count} tests, "
        "generated from the dbt manifest.\n",
        "### Lineage\n",
        lineage(models, sources, manifest),
        "### Sources\n",
    ]
    for src in sources:
        location = src["config"].get("external_location") or src.get("relation_name")
        out += [
            f"#### `{src['source_name']}.{src['name']}`\n",
            f"{cell(src.get('description'))}\n",
            f"- **Location:** `{location}`\n",
            columns_table(src, tests),
        ]

    out.append("### Models\n")
    for model in models:
        parents = [
            f"`{p.split('.')[-1]}`" if p.startswith("model.") else f"`{'.'.join(p.split('.')[-2:])}`"
            for p in manifest["parent_map"].get(model["unique_id"], [])
            if p.startswith(("model.", "source."))
        ]
        out += [
            f"#### `{model['name']}`\n",
            f"{cell(model.get('description')) or '_No description._'}\n",
            f"- **Materialized as:** {model['config'].get('materialized')}",
            f"- **File:** [`analytics/{model['original_file_path']}`](analytics/{model['original_file_path']})",
            f"- **Depends on:** {', '.join(parents) or 'nothing'}\n",
            columns_table(model, tests),
        ]
    return "\n".join(out)


def main():
    if not MANIFEST.exists():
        sys.exit(f"{MANIFEST} not found. Run `uv run dbt parse` inside analytics/ first.")
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    readme = README.read_text(encoding="utf-8")
    if START not in readme or END not in readme:
        sys.exit(f"{README} needs the markers:\n{START}\n{END}")

    before, rest = readme.split(START, 1)
    _, after = rest.split(END, 1)
    README.write_text(f"{before}{START}\n\n{build_docs(manifest)}\n{END}{after}", encoding="utf-8")
    print(f"Updated the generated section of {README}")


if __name__ == "__main__":
    main()
